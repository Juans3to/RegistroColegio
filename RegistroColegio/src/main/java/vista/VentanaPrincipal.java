    private void btnAgregarProfesorActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarProfesorActionPerformed
        // 1. La Vista valida que no haya campos vacíos
        if (hayVacios(txtProfNombre, txtProfDireccion, txtProfTelefono, txtProfFecha,
                txtProfCedula, txtProfArea, txtProfSalarioHora, txtProfHoras)) {
            JOptionPane.showMessageDialog(this, "Debes llenar todos los campos del profesor.");
            return;
        }
        try {
            // 2. Extraer y convertir las entradas de texto
            String nombre = txtProfNombre.getText().trim();
            String direccion = txtProfDireccion.getText().trim();
            String telefono = txtProfTelefono.getText().trim();
            LocalDate fechaNac = LocalDate.parse(txtProfFecha.getText().trim());
            String cedula = txtProfCedula.getText().trim();
            String area = txtProfArea.getText().trim();
            double salarioHora = Double.parseDouble(txtProfSalarioHora.getText().trim());
            int horasDictadas = Integer.parseInt(txtProfHoras.getText().trim());

            controlador.agregarProfesor(nombre, direccion, telefono, fechaNac, cedula, area, salarioHora, horasDictadas);

            // 3. Mensaje de éxito y limpieza de la interfaz
            JOptionPane.showMessageDialog(this, "Profesor registrado exitosamente.");
            limpiar(txtProfNombre, txtProfDireccion, txtProfTelefono, txtProfFecha,
                    txtProfCedula, txtProfArea, txtProfSalarioHora, txtProfHoras);

        } catch (DateTimeParseException ex) {
            JOptionPane.showMessageDialog(this, "La fecha debe tener el formato AAAA-MM-DD (ej. 1985-03-02).");
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Salario por hora y horas dictadas deben ser números.");
        } catch (IllegalArgumentException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage());
        }
    }//GEN-LAST:event_btnAgregarProfesorActionPerformed

