    private void btnImprimirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnImprimirActionPerformed
        // TODO add your handling code here:

        if (txtAreaReporte.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Primero genera un reporte para imprimir.");
            return;
        }
        try {
            txtAreaReporte.print();
        } catch (PrinterException ex) {
            JOptionPane.showMessageDialog(this, "No se pudo imprimir: " + ex.getMessage());
        }
    }//GEN-LAST:event_btnImprimirActionPerformed

