    private boolean hayVacios(JTextField... campos) {
        for (JTextField c : campos) {
            if (c.getText().trim().isEmpty()) {
                return true;
            }
        }
        return false;
    }

    private void limpiar(JTextField... campos) {
        for (JTextField c : campos) {
            c.setText("");
        }
    }


